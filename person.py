def draw_rectangle(x, y, width, height, fill_color, line_color="black"):
    t.penup()
    t.goto(x, y)
    t.setheading(0)
    t.pencolor(line_color)
    t.fillcolor(fill_color)
    t.pendown()
    t.begin_fill()
    for _ in range(2):
        t.forward(width)
        t.right(90)
        t.forward(height)
        t.right(90)
    t.end_fill()

